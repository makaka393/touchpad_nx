#!/usr/bin/env python3
"""Turns the SVG pictograms listed in assets/icons.txt into what the overlay embeds.

Writes core/icon_data.bin (one 56x56 mask per icon, 4 bits of coverage per pixel, two pixels
per byte, low nibble first) and core/icon_list.inc (the same list as C++ ICON(id, "name")
lines). Needs cairosvg and Pillow; the outputs are committed, so a normal build does not.

    python3 tools/make_icons.py
"""
import io
import os
import sys

import cairosvg
from PIL import Image

SIZE = 56    # mask is SIZE x SIZE
INNER = 52   # the drawing fits in the middle INNER x INNER, leaving a clear rim

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
icons = []
with open(os.path.join(root, "assets", "icons.txt"), encoding="utf-8") as manifest:
    for line in manifest:
        line = line.split("#")[0].split()
        if len(line) == 3:
            icons.append(line)

data = bytearray()
for ident, name, svg in icons:
    path = os.path.join(root, "assets", "fontawesome", svg + ".svg")
    big = Image.open(io.BytesIO(cairosvg.svg2png(url=path, output_height=INNER * 8))).convert("RGBA")
    alpha = big.split()[3]
    scale = INNER / max(alpha.width / 8, alpha.height / 8, INNER)
    width = max(1, round(alpha.width / 8 * scale))
    height = max(1, round(alpha.height / 8 * scale))
    alpha = alpha.resize((width, height), Image.LANCZOS)
    mask = Image.new("L", (SIZE, SIZE), 0)
    mask.paste(alpha, ((SIZE - width) // 2, (SIZE - height) // 2))
    pixels = [min(15, (v + 8) // 17) for v in mask.tobytes()]
    for i in range(0, len(pixels), 2):
        data.append(pixels[i] | (pixels[i + 1] << 4))

with open(os.path.join(root, "core", "icon_data.bin"), "wb") as out:
    out.write(data)
with open(os.path.join(root, "core", "icon_list.inc"), "w", encoding="utf-8") as out:
    out.write("// Generated by tools/make_icons.py from assets/icons.txt. Do not edit.\n")
    for ident, name, svg in icons:
        out.write('ICON(%s, "%s")\n' % (ident, name))
print("%d icons, %d bytes" % (len(icons), len(data)), file=sys.stderr)
